const fs = require('fs'), vm = require('vm');
const html = fs.readFileSync('ui/index.html', 'utf8');
const b64 = /data-wasm="([^"]+)"/.exec(html)[1];
(async () => {
  const { instance } = await WebAssembly.instantiate(Buffer.from(b64, 'base64'), {});
  const ex = instance.exports;
  const sandbox = { window: {}, console, TextDecoder, TextEncoder, Uint8Array, Int32Array, Float64Array, Math, Date, Error, Proxy, Object };
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync('.tmp-check/s2.js', 'utf8'), sandbox);
  const k = sandbox.window.__loadJsKernel();
  const ha = ex.sim_new_micro(), hb = k.sim_new_micro();
  console.log('handles', ha, hb, typeof hb);
  const t = 'N', buf = Buffer.from(t);
  const pa = ex.alloc(buf.length); new Uint8Array(ex.memory.buffer).set(buf, pa);
  console.log('rcA', ex.sim_tick(ha, 1n, pa, buf.length, 0n));
  const la = ex.frame_buf_len(), fa = ex.frame_buf_ptr();
  console.log('A len', la, 'ptr', fa, typeof la);
  const pb = k.alloc(buf.length);
  const km = k.memory.buffer ? new Uint8Array(k.memory.buffer) : new Uint8Array(k.memory);
  km.set(buf, pb);
  console.log('rcB', k.sim_tick(hb, 1, pb, buf.length, 0));
  const lb = k.frame_buf_len(), fb = k.frame_buf_ptr();
  console.log('B len', lb, 'ptr', fb, typeof lb, typeof fb);
  const A = Buffer.from(new Uint8Array(ex.memory.buffer).slice(fa, fa + Number(la)));
  const B = Buffer.from(km.slice(Number(fb), Number(fb) + Number(lb)));
  console.log('equal', A.equals(B), 'lenA', A.length, 'lenB', B.length);
  console.log('A head', A.slice(0, 24).toString('hex'));
  console.log('B head', B.slice(0, 24).toString('hex'));
})();
